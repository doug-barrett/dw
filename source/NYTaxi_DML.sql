    CAST(CURRENT_TIMESTAMP AS TIMESTAMP),
    CAST('2999-12-31 00:00:00' AS TIMESTAMP)
FROM NY_TAXI.SILVER.WRK_VENDOR;

INSERT INTO NY_TAXI.SILVER.DIM_RATE_CODE
    (RATE_CODE_ID, RATE_CODE, SYSTEM_VERSION, SYSTEM_CURRENT_FLAG,
     SYSTEM_CREATE_DATE, SYSTEM_UPDATE_DATE, SYSTEM_END_DATE)
SELECT
    RATE_CODE_ID,
    RATE_CODE,
    1,
    'Y',
    CAST(CURRENT_TIMESTAMP AS TIMESTAMP),
    CAST(CURRENT_TIMESTAMP AS TIMESTAMP),
    CAST('2999-12-31 00:00:00' AS TIMESTAMP)
FROM NY_TAXI.SILVER.WRK_RATE_CODE;

INSERT INTO NY_TAXI.SILVER.DIM_PAYMENT_TYPE
    (PAYMENT_TYPE_ID, PAYMENT_TYPE, SYSTEM_VERSION, SYSTEM_CURRENT_FLAG,
     SYSTEM_CREATE_DATE, SYSTEM_UPDATE_DATE, SYSTEM_END_DATE)
SELECT
    PAYMENT_TYPE_ID,
    PAYMENT_TYPE,
    1,
    'Y',
    CAST(CURRENT_TIMESTAMP AS TIMESTAMP),
    CAST(CURRENT_TIMESTAMP AS TIMESTAMP),
    CAST('2999-12-31 00:00:00' AS TIMESTAMP)
FROM NY_TAXI.SILVER.WRK_PAYMENT_TYPE;

INSERT INTO NY_TAXI.SILVER.DIM_LOCATION
    (LOCATION_ID, BOROUGH, ZONE, SERVICE_ZONE, FILENAME, SYSTEM_VERSION,
     SYSTEM_CURRENT_FLAG, SYSTEM_CREATE_DATE, SYSTEM_UPDATE_DATE, SYSTEM_END_DATE)
SELECT
    LOCATION_ID,
    BOROUGH,
    ZONE,
    SERVICE_ZONE,
    FILENAME,
    1,
    'Y',
    CAST(CURRENT_TIMESTAMP AS TIMESTAMP),
    CAST(CURRENT_TIMESTAMP AS TIMESTAMP),
    CAST('2999-12-31 00:00:00' AS TIMESTAMP)
FROM NY_TAXI.SILVER.WRK_LOCATION;

-- DIM_PICKUP_LOCATION / DIM_DROPOFF_LOCATION are role-playing VIEWS
-- over DIM_LOCATION (defined in NYTaxi_DDL.sql) - no load step.

-- =====================================================================
-- SILVER fact load
-- Joins the stage to the (role-playing) dimensions to resolve surrogate keys.
-- =====================================================================
INSERT INTO NY_TAXI.SILVER.FCT_YELLOW_CAB_TRIPS1
    (TRIP_ID, DIM_PICKUP_LOCATION_KEY, DIM_DROPOFF_LOCATION_KEY, DIM_PAYMENT_TYPE_KEY,
     DIM_RATE_CODE_KEY, DIM_VENDOR_KEY, VENDOR_ID, PAYMENT_TYPE_ID, RATE_CODE_ID,
     PICKUP_DATETIME, DROPOFF_DATETIME, DO_LOCATION_ID, PU_LOCATION_ID, TRIP_DISTANCE,
     AIRPORT_FEE, CBD_CONGESTION_FEE, CONGESTION_SURCHARGE, EXTRA, FARE_AMOUNT,
     IMPROVEMENT_SURCHARGE, MTA_TAX, PASSENGER_COUNT, STORE_AND_FWD_FLAG, TIP_AMOUNT,
     TOLLS_AMOUNT, TOTAL_AMOUNT, TPEP_PICKUP_DATETIME, TPEP_DROPOFF_DATETIME,
     TRIP_DURATION_MINUTES, AVERAGE_SPEED_MPH, FILE_NAME,
     SYSTEM_CREATE_DATE, SYSTEM_UPDATE_DATE)
SELECT
    T.TRIP_ID,
    PU.DIM_PICKUP_LOCATION_KEY,
    DO.DIM_DROPOFF_LOCATION_KEY,
    PT.DIM_PAYMENT_TYPE_KEY,
    RC.DIM_RATE_CODE_KEY,
    V.DIM_VENDOR_KEY,
    T.VENDOR_ID,
    T.PAYMENT_TYPE_ID,
    T.RATE_CODE_ID,
    T.PICKUP_DATETIME,
    T.DROPOFF_DATETIME,
    T.DO_LOCATION_ID,
    T.PU_LOCATION_ID,
    T.TRIP_DISTANCE,
    T.AIRPORT_FEE,
    T.CBD_CONGESTION_FEE,
    T.CONGESTION_SURCHARGE,
    T.EXTRA,
    T.FARE_AMOUNT,
    T.IMPROVEMENT_SURCHARGE,
    T.MTA_TAX,
    T.PASSENGER_COUNT,
    T.STORE_AND_FWD_FLAG,
    T.TIP_AMOUNT,
    T.TOLLS_AMOUNT,
    T.TOTAL_AMOUNT,
    T.TPEP_PICKUP_DATETIME,
    T.TPEP_DROPOFF_DATETIME,
    T.TRIP_DURATION_MINUTES,
    T.AVERAGE_SPEED_MPH,
    T.FILE_NAME,
    CAST(CURRENT_TIMESTAMP AS TIMESTAMP),
    CAST(CURRENT_TIMESTAMP AS TIMESTAMP)
FROM NY_TAXI.SILVER.WRK_YELLOW_CAB_TRIPS T
LEFT JOIN NY_TAXI.SILVER.DIM_PICKUP_LOCATION PU
       ON T.PU_LOCATION_ID = PU.PU_LOCATION_ID
      AND PU.SYSTEM_CURRENT_FLAG = 'Y'
LEFT JOIN NY_TAXI.SILVER.DIM_DROPOFF_LOCATION DO
       ON T.DO_LOCATION_ID = DO.DO_LOCATION_ID
      AND DO.SYSTEM_CURRENT_FLAG = 'Y'
LEFT JOIN NY_TAXI.SILVER.DIM_PAYMENT_TYPE PT
       ON T.PAYMENT_TYPE_ID = PT.PAYMENT_TYPE_ID
      AND PT.SYSTEM_CURRENT_FLAG = 'Y'
LEFT JOIN NY_TAXI.SILVER.DIM_RATE_CODE RC
       ON T.RATE_CODE_ID = RC.RATE_CODE_ID
      AND RC.SYSTEM_CURRENT_FLAG = 'Y'
LEFT JOIN NY_TAXI.SILVER.DIM_VENDOR V
       ON T.VENDOR_ID = V.VENDOR_ID
      AND V.SYSTEM_CURRENT_FLAG = 'Y';

-- VW_LOCATION and VW_YELLOW_CAB_TRIPS are VIEWS (defined in NYTaxi_DDL.sql) - no load step.

