-- =====================================================================
-- NY Taxi demo  |  Load logic (transforms)
-- Run in order. Structures defined in NYTaxi_DDL.sql.
-- BRONZE (source) -> SILVER stage -> SILVER dim -> SILVER fact -> views
--                 -> GOLD dim -> PLATINUM view
-- =====================================================================
USE DATABASE NY_TAXI;

-- =====================================================================
-- SILVER stage (work) loads
-- =====================================================================

-- Pass-through stages (1:1 from source)
INSERT INTO NY_TAXI.SILVER.WRK_VENDOR
SELECT VENDOR_ID, VENDOR_NAME
FROM NY_TAXI.BRONZE.VENDOR;

INSERT INTO NY_TAXI.SILVER.WRK_PAYMENT_TYPE
SELECT PAYMENT_TYPE_ID, PAYMENT_TYPE
FROM NY_TAXI.BRONZE.PAYMENT_TYPE;

INSERT INTO NY_TAXI.SILVER.WRK_LOCATION
SELECT LOCATION_ID, BOROUGH, ZONE, SERVICE_ZONE, FILENAME
FROM NY_TAXI.BRONZE.LOCATION;

-- Rate code: standardize + enrich with NYC TLC rate descriptions and flags
INSERT INTO NY_TAXI.SILVER.WRK_RATE_CODE
SELECT
    RATE_CODE_ID,
    RATE_CODE,
    CAST(RATE_CODE_ID AS NUMBER)        AS RATE_CODE_NUM,
    INITCAP(TRIM(RATE_CODE))            AS RATE_CODE_CLEAN,
    CASE CAST(RATE_CODE_ID AS NUMBER)
         WHEN 1 THEN 'Standard Rate'
         WHEN 2 THEN 'JFK'
         WHEN 3 THEN 'Newark'
         WHEN 4 THEN 'Nassau or Westchester'
         WHEN 5 THEN 'Negotiated Fare'
         WHEN 6 THEN 'Group Ride'
         ELSE 'Unknown'
    END                                 AS RATE_CODE_DESC,
    CASE
         WHEN CAST(RATE_CODE_ID AS NUMBER) IN (2, 3) THEN 'Airport'
         WHEN CAST(RATE_CODE_ID AS NUMBER) = 5       THEN 'Negotiated'
         WHEN CAST(RATE_CODE_ID AS NUMBER) = 6       THEN 'Shared'
         WHEN CAST(RATE_CODE_ID AS NUMBER) IN (1, 4) THEN 'Metered'
         ELSE 'Other'
    END                                 AS RATE_CODE_CATEGORY,
    CASE WHEN CAST(RATE_CODE_ID AS NUMBER) IN (2, 3)        THEN 'Y' ELSE 'N' END AS IS_AIRPORT_RATE_FLAG,
    CASE WHEN CAST(RATE_CODE_ID AS NUMBER) = 5             THEN 'Y' ELSE 'N' END AS IS_NEGOTIATED_FLAG,
    CASE WHEN CAST(RATE_CODE_ID AS NUMBER) BETWEEN 1 AND 6 THEN 'Y' ELSE 'N' END AS IS_VALID_RATE_FLAG
FROM NY_TAXI.BRONZE.RATE_CODE;

-- Trips: carry columns + derive trip duration and average speed
INSERT INTO NY_TAXI.SILVER.WRK_YELLOW_CAB_TRIPS
SELECT
    TRIP_ID,
    VENDOR_ID,
    PAYMENT_TYPE_ID,
    RATE_CODE_ID,
    PICKUP_DATETIME,
    DROPOFF_DATETIME,
    DO_LOCATION_ID,
    PU_LOCATION_ID,
    TRIP_DISTANCE,
    AIRPORT_FEE,
    CBD_CONGESTION_FEE,
    CONGESTION_SURCHARGE,
    EXTRA,
    FARE_AMOUNT,
    IMPROVEMENT_SURCHARGE,
    MTA_TAX,
    PASSENGER_COUNT,
    STORE_AND_FWD_FLAG,
    TIP_AMOUNT,
    TOLLS_AMOUNT,
    TOTAL_AMOUNT,
    TPEP_PICKUP_DATETIME,
    TPEP_DROPOFF_DATETIME,
    DATEDIFF('SECOND', PICKUP_DATETIME, DROPOFF_DATETIME) / 60.0 AS TRIP_DURATION_MINUTES,
    CASE
         WHEN DATEDIFF('SECOND', PICKUP_DATETIME, DROPOFF_DATETIME) > 0
         THEN TRIP_DISTANCE / (DATEDIFF('SECOND', PICKUP_DATETIME, DROPOFF_DATETIME) / 3600.0)
         ELSE NULL
    END                                                         AS AVERAGE_SPEED_MPH,
    FILE_NAME
FROM NY_TAXI.BRONZE.YELLOW_CAB_TRIPS;

-- Drivers: carry columns + derive tenure in years
INSERT INTO NY_TAXI.SILVER.STG_DRIVERS
SELECT
    DRIVER_ID,
    VENDOR_ID,
    FIRST_NAME,
    LAST_NAME,
    LICENSE_NUMBER,
    LICENSE_EXPIRY,
    PHONE,
    EMAIL,
    HIRE_DATE,
    RATING,
    IS_ACTIVE,
    DATEDIFF(YEAR, HIRE_DATE, CURRENT_DATE) AS TENURE
FROM NY_TAXI.BRONZE.DRIVERS;

-- =====================================================================
-- SILVER dimension loads  (surrogate key auto-generated; current version)
-- =====================================================================
INSERT INTO NY_TAXI.SILVER.DIM_VENDOR
    (VENDOR_ID, VENDOR_NAME, SYSTEM_VERSION, SYSTEM_CURRENT_FLAG,
