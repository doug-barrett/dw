    DIM_LOCATION_KEY AS DIM_PICKUP_LOCATION_KEY,
    LOCATION_ID      AS PU_LOCATION_ID,
    BOROUGH          AS PU_BOROUGH,
    ZONE             AS PU_ZONE,
    SERVICE_ZONE     AS PU_SERVICE_ZONE,
    FILENAME,
    SYSTEM_VERSION,
    SYSTEM_CURRENT_FLAG,
    SYSTEM_CREATE_DATE,
    SYSTEM_UPDATE_DATE,
    SYSTEM_END_DATE
