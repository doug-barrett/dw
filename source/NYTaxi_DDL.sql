-- ---- Reporting views ----
CREATE OR REPLACE VIEW NY_TAXI.SILVER.VW_LOCATION AS
SELECT
    DIM_LOCATION_KEY,
    LOCATION_ID,
    BOROUGH,
    ZONE,
    SERVICE_ZONE,
    FILENAME,
    SYSTEM_VERSION,
    SYSTEM_CURRENT_FLAG,
    SYSTEM_CREATE_DATE,
    SYSTEM_UPDATE_DATE,
    SYSTEM_END_DATE
FROM NY_TAXI.SILVER.DIM_LOCATION;

CREATE OR REPLACE VIEW NY_TAXI.SILVER.VW_YELLOW_CAB_TRIPS AS
SELECT
    F.TRIP_ID,
    F.VENDOR_ID,
    F.PAYMENT_TYPE_ID,
    F.RATE_CODE_ID,
    F.PICKUP_DATETIME,
    F.DROPOFF_DATETIME,
    F.DO_LOCATION_ID,
    F.PU_LOCATION_ID,
    F.TRIP_DISTANCE,
    F.AIRPORT_FEE,
    F.CBD_CONGESTION_FEE,
    F.CONGESTION_SURCHARGE,
    F.EXTRA,
    F.FARE_AMOUNT,
    F.IMPROVEMENT_SURCHARGE,
    F.MTA_TAX,
    F.PASSENGER_COUNT,
    F.STORE_AND_FWD_FLAG,
    F.TIP_AMOUNT,
    F.TOLLS_AMOUNT,
    F.TOTAL_AMOUNT,
    DO.DO_BOROUGH,
    DO.DO_ZONE,
    DO.DO_SERVICE_ZONE,
    PU.PU_BOROUGH,
    PU.PU_ZONE,
    PU.PU_SERVICE_ZONE,
    RC.RATE_CODE,
    V.VENDOR_NAME
FROM NY_TAXI.SILVER.FCT_YELLOW_CAB_TRIPS1 F
LEFT JOIN NY_TAXI.SILVER.DIM_DROPOFF_LOCATION DO
       ON F.DIM_DROPOFF_LOCATION_KEY = DO.DIM_DROPOFF_LOCATION_KEY
LEFT JOIN NY_TAXI.SILVER.DIM_PICKUP_LOCATION PU
       ON F.DIM_PICKUP_LOCATION_KEY = PU.DIM_PICKUP_LOCATION_KEY
LEFT JOIN NY_TAXI.SILVER.DIM_RATE_CODE RC
       ON F.DIM_RATE_CODE_KEY = RC.DIM_RATE_CODE_KEY
LEFT JOIN NY_TAXI.SILVER.DIM_VENDOR V
       ON F.DIM_VENDOR_KEY = V.DIM_VENDOR_KEY;

