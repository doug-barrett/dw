CREATE OR REPLACE PROCEDURE "BUILD_DRIVER_360"()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
    CREATE OR REPLACE TABLE NY_TAXI.SILVER.STG_DRIVER AS
    WITH trip_vendors AS (
        SELECT DISTINCT VENDOR_ID AS TV_ID, VENDOR_NAME AS TV_NAME
        FROM NY_TAXI.GOLD.FCT_YELLOW_CAB_TRIPS
        WHERE VENDOR_ID IS NOT NULL
    ),
    numbered_vendors AS (
        SELECT TV_ID, TV_NAME,
               ROW_NUMBER() OVER (ORDER BY TV_ID) - 1 AS vendor_idx,
               COUNT(*) OVER () AS vendor_cnt
        FROM trip_vendors
    ),
    drivers_numbered AS (
        SELECT d.*,
               v.VENDOR_NAME,
               ROW_NUMBER() OVER (ORDER BY d.DRIVER_ID) - 1 AS driver_idx
        FROM NY_TAXI.BRONZE.DRIVERS d
        LEFT JOIN NY_TAXI.BRONZE.VENDOR v ON d.VENDOR_ID = v.VENDOR_ID
    )
    SELECT
        dn.DRIVER_ID, dn.VENDOR_ID, dn.FIRST_NAME, dn.LAST_NAME,
        dn.FIRST_NAME || '' '' || dn.LAST_NAME AS FULL_NAME,
        dn.LICENSE_NUMBER, dn.LICENSE_EXPIRY, dn.PHONE, dn.EMAIL, dn.HIRE_DATE,
        dn.RATING, dn.IS_ACTIVE, dn.VENDOR_NAME,
        nv.TV_ID AS TRIP_VENDOR_ID, nv.TV_NAME AS TRIP_VENDOR_NAME,
        ROUND(DATEDIFF(''day'', dn.HIRE_DATE, CURRENT_DATE()) / 365.25, 2) AS TENURE_YEARS
    FROM drivers_numbered dn
    INNER JOIN numbered_vendors nv
        ON MOD(dn.driver_idx, nv.vendor_cnt) = nv.vendor_idx;

    CREATE OR REPLACE TABLE NY_TAXI.SILVER.STG_DRIVER_TRIPS AS
    WITH vendor_drivers AS (
        SELECT DRIVER_ID, TRIP_VENDOR_ID,
               ROW_NUMBER() OVER (PARTITION BY TRIP_VENDOR_ID ORDER BY DRIVER_ID) - 1 AS drv_idx,
               COUNT(*) OVER (PARTITION BY TRIP_VENDOR_ID) AS drv_cnt
        FROM NY_TAXI.SILVER.STG_DRIVER
    )
    SELECT
        vd.DRIVER_ID, vd.TRIP_VENDOR_ID,
        t.TRIP_ID, t.PASSENGER_COUNT, t.TRIP_DISTANCE, t.TRIP_DURATION_MINUTES,
        t.TRIP_AVG_SPEED, t.PICKUP_DATETIME, t.DROPOFF_DATETIME,
        t.PU_BOROUGH, t.DO_BOROUGH, t.PAYMENT_TYPE, t.RATE_CODE,
        t.FARE_AMOUNT, t.TIP_AMOUNT, t.TOLLS_AMOUNT,
        t.CONGESTION_SURCHARGE, t.IMPROVEMENT_SURCHARGE, t.AIRPORT_FEE,
        t.MTA_TAX, t.EXTRA, t.TOTAL_AMOUNT
    FROM NY_TAXI.GOLD.FCT_YELLOW_CAB_TRIPS t
    INNER JOIN vendor_drivers vd
        ON t.VENDOR_ID = vd.TRIP_VENDOR_ID
       AND MOD(t.TRIP_ID, vd.drv_cnt) = vd.drv_idx;

    CREATE OR REPLACE TABLE NY_TAXI.SILVER.STG_DRIVER_TRIP_AGG AS
    WITH trip_agg AS (
        SELECT
            DRIVER_ID, TRIP_VENDOR_ID,
            COUNT(*) AS TOTAL_TRIPS,
            COALESCE(SUM(PASSENGER_COUNT), 0) AS TOTAL_PASSENGERS,
            COALESCE(SUM(TRIP_DISTANCE), 0) AS TOTAL_DISTANCE_MILES,
            COALESCE(SUM(TRIP_DURATION_MINUTES), 0) AS TOTAL_DURATION_MINUTES,
            AVG(TRIP_DISTANCE) AS AVG_TRIP_DISTANCE,
            AVG(TRIP_DURATION_MINUTES) AS AVG_TRIP_DURATION,
            AVG(TRIP_AVG_SPEED) AS AVG_SPEED_MPH,
            COALESCE(SUM(FARE_AMOUNT), 0) AS TOTAL_FARE_AMOUNT,
            COALESCE(SUM(TIP_AMOUNT), 0) AS TOTAL_TIP_AMOUNT,
            COALESCE(SUM(TOLLS_AMOUNT), 0) AS TOTAL_TOLLS_AMOUNT,
            COALESCE(SUM(CONGESTION_SURCHARGE), 0) + COALESCE(SUM(IMPROVEMENT_SURCHARGE), 0) + COALESCE(SUM(AIRPORT_FEE), 0) AS TOTAL_SURCHARGES,
            COALESCE(SUM(TOTAL_AMOUNT), 0) AS TOTAL_REVENUE,
            AVG(FARE_AMOUNT) AS AVG_FARE_PER_TRIP,
            AVG(TIP_AMOUNT) AS AVG_TIP_PER_TRIP,
            CASE WHEN SUM(FARE_AMOUNT) > 0 THEN ROUND(SUM(TIP_AMOUNT) / SUM(FARE_AMOUNT) * 100, 2) ELSE 0 END AS TIP_PERCENTAGE,
            MIN(PICKUP_DATETIME) AS FIRST_TRIP_DATE,
            MAX(PICKUP_DATETIME) AS LAST_TRIP_DATE,
            COUNT(DISTINCT DATE(PICKUP_DATETIME)) AS ACTIVE_DAYS,
            SUM(CASE WHEN PAYMENT_TYPE = ''Credit card'' THEN 1 ELSE 0 END) * 100.0 / NULLIF(COUNT(*), 0) AS PCT_CREDIT_CARD,
            SUM(CASE WHEN PAYMENT_TYPE = ''Cash'' THEN 1 ELSE 0 END) * 100.0 / NULLIF(COUNT(*), 0) AS PCT_CASH
        FROM NY_TAXI.SILVER.STG_DRIVER_TRIPS
        GROUP BY DRIVER_ID, TRIP_VENDOR_ID
    ),
    top_pu AS (
        SELECT DRIVER_ID, PU_BOROUGH AS BOROUGH,
               ROW_NUMBER() OVER (PARTITION BY DRIVER_ID ORDER BY COUNT(*) DESC) AS rn
        FROM NY_TAXI.SILVER.STG_DRIVER_TRIPS WHERE PU_BOROUGH IS NOT NULL
        GROUP BY DRIVER_ID, PU_BOROUGH
    ),
    top_do AS (
        SELECT DRIVER_ID, DO_BOROUGH AS BOROUGH,
               ROW_NUMBER() OVER (PARTITION BY DRIVER_ID ORDER BY COUNT(*) DESC) AS rn
        FROM NY_TAXI.SILVER.STG_DRIVER_TRIPS WHERE DO_BOROUGH IS NOT NULL
        GROUP BY DRIVER_ID, DO_BOROUGH
    )
    SELECT a.*, pu.BOROUGH AS TOP_PICKUP_BOROUGH, do2.BOROUGH AS TOP_DROPOFF_BOROUGH
    FROM trip_agg a
    LEFT JOIN top_pu pu ON a.DRIVER_ID = pu.DRIVER_ID AND pu.rn = 1
    LEFT JOIN top_do do2 ON a.DRIVER_ID = do2.DRIVER_ID AND do2.rn = 1;

    CREATE OR REPLACE TABLE NY_TAXI.SILVER.STG_DRIVER_LTV AS
    WITH base AS (
        SELECT
            sd.DRIVER_ID, sd.FULL_NAME, sd.VENDOR_NAME, sd.TRIP_VENDOR_NAME,
            sd.IS_ACTIVE, sd.HIRE_DATE, sd.TENURE_YEARS, sd.RATING,
            ta.TOTAL_TRIPS, ta.TOTAL_REVENUE, ta.TOTAL_TIP_AMOUNT, ta.ACTIVE_DAYS,
            CASE WHEN ta.TOTAL_TRIPS > 0 THEN ta.TOTAL_REVENUE / ta.TOTAL_TRIPS ELSE 0 END AS AVG_REVENUE_PER_TRIP,
            CASE WHEN ta.ACTIVE_DAYS > 0 THEN ta.TOTAL_TRIPS * 1.0 / ta.ACTIVE_DAYS ELSE 0 END AS AVG_TRIPS_PER_ACTIVE_DAY,
            CASE WHEN sd.TENURE_YEARS > 0 THEN ta.TOTAL_REVENUE / (sd.TENURE_YEARS * 12) ELSE ta.TOTAL_REVENUE END AS MONTHLY_AVG_REVENUE
        FROM NY_TAXI.SILVER.STG_DRIVER sd
        LEFT JOIN NY_TAXI.SILVER.STG_DRIVER_TRIP_AGG ta ON sd.DRIVER_ID = ta.DRIVER_ID
    ),
    ltv_calc AS (
        SELECT *, MONTHLY_AVG_REVENUE * 60 AS LTV_ESTIMATED,
            RANK() OVER (ORDER BY TOTAL_REVENUE DESC NULLS LAST) AS REVENUE_RANK,
            RANK() OVER (ORDER BY MONTHLY_AVG_REVENUE * 60 DESC NULLS LAST) AS LTV_RANK
        FROM base
    )
    SELECT DRIVER_ID, FULL_NAME, VENDOR_NAME, TRIP_VENDOR_NAME,
        IS_ACTIVE, HIRE_DATE, TENURE_YEARS, RATING,
        TOTAL_TRIPS, TOTAL_REVENUE, TOTAL_TIP_AMOUNT,
        AVG_REVENUE_PER_TRIP, AVG_TRIPS_PER_ACTIVE_DAY,
        MONTHLY_AVG_REVENUE, LTV_ESTIMATED, REVENUE_RANK, LTV_RANK,
        CASE
            WHEN LTV_RANK <= CEIL((SELECT COUNT(*) FROM ltv_calc) * 0.1) THEN ''PLATINUM''
            WHEN LTV_RANK <= CEIL((SELECT COUNT(*) FROM ltv_calc) * 0.3) THEN ''GOLD''
            WHEN LTV_RANK <= CEIL((SELECT COUNT(*) FROM ltv_calc) * 0.6) THEN ''SILVER''
            ELSE ''BRONZE''
        END AS DRIVER_SEGMENT
    FROM ltv_calc;

    CREATE TABLE IF NOT EXISTS NY_TAXI.GOLD.DIM_DRIVER (
        DIM_DRIVER_KEY      NUMBER(38,0) IDENTITY,
        DRIVER_ID           NUMBER(38,0),
        VENDOR_ID           NUMBER(38,0),
        FIRST_NAME          VARCHAR(50),
        LAST_NAME           VARCHAR(50),
        FULL_NAME           VARCHAR(101),
        LICENSE_NUMBER      VARCHAR(10),
        LICENSE_EXPIRY      DATE,
        PHONE               VARCHAR(14),
        EMAIL               VARCHAR(100),
        HIRE_DATE           DATE,
        RATING              NUMBER(2,1),
        IS_ACTIVE           BOOLEAN,
        VENDOR_NAME         VARCHAR,
        TRIP_VENDOR_ID      FLOAT,
        TRIP_VENDOR_NAME    VARCHAR(33),
        TENURE_YEARS        NUMBER(5,2),
        SYSTEM_VERSION      NUMBER(38,0),
        SYSTEM_CURRENT_FLAG VARCHAR(1),
        SYSTEM_START_DATE   TIMESTAMP_NTZ,
        SYSTEM_END_DATE     TIMESTAMP_NTZ,
        SYSTEM_CREATE_DATE  TIMESTAMP_NTZ,
        SYSTEM_UPDATE_DATE  TIMESTAMP_NTZ
    );

    UPDATE NY_TAXI.GOLD.DIM_DRIVER tgt
    SET tgt.SYSTEM_CURRENT_FLAG = ''N'',
        tgt.SYSTEM_END_DATE    = CURRENT_TIMESTAMP(),
        tgt.SYSTEM_UPDATE_DATE = CURRENT_TIMESTAMP()
    FROM NY_TAXI.SILVER.STG_DRIVER src
    WHERE tgt.DRIVER_ID = src.DRIVER_ID
      AND tgt.SYSTEM_CURRENT_FLAG = ''Y''
      AND (   tgt.FIRST_NAME       IS DISTINCT FROM src.FIRST_NAME
           OR tgt.LAST_NAME        IS DISTINCT FROM src.LAST_NAME
           OR tgt.LICENSE_NUMBER    IS DISTINCT FROM src.LICENSE_NUMBER
           OR tgt.LICENSE_EXPIRY    IS DISTINCT FROM src.LICENSE_EXPIRY
           OR tgt.PHONE            IS DISTINCT FROM src.PHONE
           OR tgt.EMAIL            IS DISTINCT FROM src.EMAIL
           OR tgt.RATING           IS DISTINCT FROM src.RATING
           OR tgt.IS_ACTIVE        IS DISTINCT FROM src.IS_ACTIVE
           OR tgt.VENDOR_NAME      IS DISTINCT FROM src.VENDOR_NAME
           OR tgt.TRIP_VENDOR_ID   IS DISTINCT FROM src.TRIP_VENDOR_ID
      );

    INSERT INTO NY_TAXI.GOLD.DIM_DRIVER (
        DRIVER_ID, VENDOR_ID, FIRST_NAME, LAST_NAME, FULL_NAME,
        LICENSE_NUMBER, LICENSE_EXPIRY, PHONE, EMAIL, HIRE_DATE,
        RATING, IS_ACTIVE, VENDOR_NAME, TRIP_VENDOR_ID, TRIP_VENDOR_NAME, TENURE_YEARS,
        SYSTEM_VERSION, SYSTEM_CURRENT_FLAG, SYSTEM_START_DATE, SYSTEM_END_DATE,
        SYSTEM_CREATE_DATE, SYSTEM_UPDATE_DATE
    )
    SELECT
        src.DRIVER_ID, src.VENDOR_ID, src.FIRST_NAME, src.LAST_NAME, src.FULL_NAME,
        src.LICENSE_NUMBER, src.LICENSE_EXPIRY, src.PHONE, src.EMAIL, src.HIRE_DATE,
        src.RATING, src.IS_ACTIVE, src.VENDOR_NAME, src.TRIP_VENDOR_ID, src.TRIP_VENDOR_NAME, src.TENURE_YEARS,
        COALESCE(existing.max_ver, 0) + 1,
        ''Y'',
        CURRENT_TIMESTAMP(),
        ''9999-12-31''::TIMESTAMP_NTZ,
        COALESCE(existing.first_created, CURRENT_TIMESTAMP()),
        CURRENT_TIMESTAMP()
    FROM NY_TAXI.SILVER.STG_DRIVER src
    LEFT JOIN (
        SELECT DRIVER_ID, MAX(SYSTEM_VERSION) AS max_ver, MIN(SYSTEM_CREATE_DATE) AS first_created
        FROM NY_TAXI.GOLD.DIM_DRIVER
        GROUP BY DRIVER_ID
    ) existing ON src.DRIVER_ID = existing.DRIVER_ID
